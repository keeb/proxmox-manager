/**
 * @keeb/debian/preseed — renders a Debian installer preseed for an
 * unattended netinst install and publishes it to an HTTP server over SSH
 * (the PXE box). Records the matching ISO boot command so a workflow can feed
 * it to `fleet.sendKeys`.
 */
import { z } from "npm:zod@4";
import { sshExec, isValidSshHost } from "./lib/ssh.ts";

const GlobalArgs = z.object({
  sshHost: z.string().describe("SSH host of the HTTP server serving preseeds"),
  sshUser: z.string().default("root").describe("SSH user"),
  httpRoot: z.string().default("/srv/http").describe(
    "Document root on the HTTP server",
  ),
  httpBaseUrl: z.string().describe(
    "Base URL the installer fetches from (e.g. http://10.0.0.191)",
  ),
});

const PublishArgs = z.object({
  hostname: z.string().describe("Hostname for the installed system"),
  domain: z.string().default("lan").describe("DNS domain"),
  username: z.string().describe("Primary (sudo) user to create"),
  // Not marked sensitive on purpose: a short dictionary password registered
  // with the secret redactor masks that substring everywhere in the run
  // (e.g. "keeb" → "***" inside vault key names). Use a real vault secret
  // for passwords that matter.
  password: z.string().describe(
    "Primary user's password (hashed before publishing)",
  ),
  sshAuthorizedKey: z.string().describe(
    "Public key installed for root and the primary user",
  ),
  timezone: z.string().default("UTC").describe("Olson timezone"),
  packages: z.string().default("qemu-guest-agent sudo curl ca-certificates")
    .describe("Extra packages installed during the install (space-separated)"),
});

const PreseedSchema = z.object({
  hostname: z.string(),
  url: z.string().describe("URL the installer fetches the preseed from"),
  path: z.string().describe("Path on the HTTP server"),
  bootCommand: z.string().describe(
    "Keys to type at the Debian ISO boot menu (fleet.sendKeys format)",
  ),
  logs: z.string().optional(),
  timestamp: z.string(),
});

async function sha512crypt(password: string): Promise<string> {
  // @ts-ignore - Deno API
  const proc = new Deno.Command("openssl", {
    args: ["passwd", "-6", "-stdin"],
    stdin: "piped",
    stdout: "piped",
    stderr: "piped",
  }).spawn();
  const writer = proc.stdin.getWriter();
  await writer.write(new TextEncoder().encode(password));
  await writer.close();
  const { code, stdout, stderr } = await proc.output();
  if (code !== 0) {
    throw new Error(`openssl passwd failed: ${new TextDecoder().decode(stderr)}`);
  }
  return new TextDecoder().decode(stdout).trim();
}

/** Render the preseed file. Pure. */
export function renderPreseed(opts: {
  hostname: string;
  domain: string;
  username: string;
  passwordHash: string;
  sshAuthorizedKey: string;
  timezone: string;
  packages: string;
}): string {
  const key = opts.sshAuthorizedKey.trim().replace(/'/g, "");
  const u = opts.username;
  const lateCommand = [
    `mkdir -p /target/root/.ssh /target/home/${u}/.ssh`,
    `echo '${key}' > /target/root/.ssh/authorized_keys`,
    `echo '${key}' > /target/home/${u}/.ssh/authorized_keys`,
    `chmod 700 /target/root/.ssh /target/home/${u}/.ssh`,
    `chmod 600 /target/root/.ssh/authorized_keys /target/home/${u}/.ssh/authorized_keys`,
    `in-target chown -R ${u}:${u} /home/${u}/.ssh`,
    // netcfg names the box before the preseed is fetched (no hostname= on
    // the menu-driven boot line), so force it here.
    `echo ${opts.hostname} > /target/etc/hostname`,
    `sed -i 's/^127\\.0\\.1\\.1.*/127.0.1.1\\t${opts.hostname}.${opts.domain} ${opts.hostname}/' /target/etc/hosts`,
  ].join("; ");

  return `# Generated by @keeb/debian/preseed — do not edit by hand
d-i debian-installer/locale string en_US.UTF-8
d-i keyboard-configuration/xkb-keymap select us
d-i netcfg/choose_interface select auto
d-i netcfg/get_hostname string ${opts.hostname}
d-i netcfg/get_domain string ${opts.domain}
d-i netcfg/hostname string ${opts.hostname}
d-i hw-detect/load_firmware boolean false

d-i mirror/country string manual
d-i mirror/http/hostname string deb.debian.org
d-i mirror/http/directory string /debian
d-i mirror/http/proxy string

d-i passwd/root-login boolean false
d-i passwd/user-fullname string ${u}
d-i passwd/username string ${u}
d-i passwd/user-password-crypted password ${opts.passwordHash}
d-i passwd/user-default-groups string audio cdrom video sudo plugdev netdev users

d-i clock-setup/utc boolean true
d-i time/zone string ${opts.timezone}
d-i clock-setup/ntp boolean true

d-i partman-auto/disk string /dev/sda
d-i partman-auto/method string regular
d-i partman-auto/choose_recipe select atomic
d-i partman-partitioning/confirm_write_new_label boolean true
d-i partman/choose_partition select finish
d-i partman/confirm boolean true
d-i partman/confirm_nooverwrite boolean true

d-i apt-setup/cdrom/set-first boolean false
d-i apt-setup/cdrom/set-next boolean false
d-i apt-setup/cdrom/set-failed boolean false
d-i apt-setup/disable-cdrom-entries boolean true
d-i apt-setup/non-free-firmware boolean true
d-i apt-setup/services-select multiselect security, updates

tasksel tasksel/first multiselect standard, ssh-server
d-i pkgsel/include string ${opts.packages}
d-i pkgsel/upgrade select full-upgrade
popularity-contest popularity-contest/participate boolean false

d-i grub-installer/only_debian boolean true
d-i grub-installer/with_other_os boolean true
d-i grub-installer/bootdev string default

d-i preseed/late_command string ${lateCommand}
d-i finish-install/reboot_in_progress note
`;
}

export const model = {
  type: "@keeb/debian/preseed",
  version: "2026.10.13.1",
  resources: {
    "preseed": {
      description: "Published preseed and its ISO boot command",
      schema: PreseedSchema,
      lifetime: "infinite",
      garbageCollection: 10,
    },
  },
  globalArguments: GlobalArgs,
  methods: {
    publish: {
      description:
        "Render an unattended-install preseed and publish it to the HTTP server; records the ISO boot command",
      arguments: PublishArgs,
      // deno-lint-ignore no-explicit-any
      execute: async (args: any, context: any) => {
        const { sshHost, sshUser = "root", httpRoot, httpBaseUrl } =
          context.globalArgs;
        if (!isValidSshHost(sshHost)) throw new Error("sshHost is required");
        const logs: string[] = [];
        const log = (msg: string) => {
          logs.push(msg);
          console.log(msg);
        };

        const passwordHash = await sha512crypt(args.password);
        const content = renderPreseed({ ...args, passwordHash });

        const path = `${httpRoot}/preseed/${args.hostname}.cfg`;
        const url = `${httpBaseUrl.replace(/\/$/, "")}/preseed/${args.hostname}.cfg`;
        const b64 = btoa(String.fromCharCode(...new TextEncoder().encode(content)));
        await sshExec(
          sshHost,
          sshUser,
          `mkdir -p ${httpRoot}/preseed && echo '${b64}' | base64 -d > ${path} && chmod 644 ${path}`,
        );
        log(`Published preseed → ${sshHost}:${path}`);

        // Debian 13 ISOs boot through a locked-down GRUB menu: no `c`
        // command line, letters are entry hotkeys, and an idle menu
        // auto-starts the speech-synthesis installer. So navigate with arrows
        // only: Advanced options (3rd) → Automated install (7th, below
        // "Back.."). That entry boots auto=true priority=critical with no
        // url, so the installer asks for the preseed location after DHCP —
        // type it there. The preseed sets the hostname.
        const bootCommand = [
          `<down><down><enter><wait2>`,
          `<down><down><down><down><down><down><enter>`,
          `<wait60>${url}<enter>`,
        ].join("");

        const handle = await context.writeResource("preseed", args.hostname, {
          hostname: args.hostname,
          url,
          path,
          bootCommand,
          logs: logs.join("\n"),
          timestamp: new Date().toISOString(),
        });
        return { dataHandles: [handle] };
      },
    },
  },
};
